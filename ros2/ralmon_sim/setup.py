"""Package definition of ralmon_sim (ament_python).

The console scripts are the module map of docs/plan/workstreams/WS07-ros2-sim/README.md; the
modules behind them are created by WS07-T02 to WS07-T07, so later tasks do not edit this file.
"""

import os
from glob import glob

from setuptools import find_packages, setup

package_name = "ralmon_sim"


def _files(pattern: str) -> list[str]:
    """Regular files matching a glob (directories are skipped: data_files takes files only)."""
    return sorted(path for path in glob(pattern) if os.path.isfile(path))


setup(
    name=package_name,
    version="0.0.0",
    packages=find_packages(exclude=["test"]),
    data_files=[
        ("share/ament_index/resource_index/packages", ["resource/" + package_name]),
        ("share/" + package_name, ["package.xml"]),
        (os.path.join("share", package_name, "launch"), _files("launch/*.launch.py")),
        (os.path.join("share", package_name, "config"), _files("config/*.yaml")),
        (
            os.path.join("share", package_name, "config", "experiments"),
            _files("config/experiments/*.yaml"),
        ),
        (
            os.path.join("share", package_name, "config", "fault_schedules"),
            _files("config/fault_schedules/*.yaml"),
        ),
        (os.path.join("share", package_name, "worlds"), _files("worlds/*")),
    ],
    install_requires=["setuptools"],
    zip_safe=True,
    maintainer="gab",
    maintainer_email="cellomar03@gmail.com",
    description="Simulation environment of the ralmon technical validation (WS07)",
    license="NOASSERTION",
    tests_require=["pytest"],
    entry_points={
        "console_scripts": [
            "sim_device_node = ralmon_sim.sim_devices:main_device",
            "sim_gateway_node = ralmon_sim.sim_devices:main_gateway",
            "sim_backend_node = ralmon_sim.sim_devices:main_backend",
            "robot_task_node = ralmon_sim.robot_task_node:main",
            "fault_injector_node = ralmon_sim.fault_injector:main",
            "deadline_prediction = ralmon_sim.deadline_prediction:main",
            "deadline_logger_node = ralmon_sim.deadline_logger:main",
            "measure_run = ralmon_sim.measure_runner:main",
        ],
    },
)
