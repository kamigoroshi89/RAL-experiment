def _clock(ms: int) -> str:
    hours, rest = divmod(int(ms), MS_PER_HOUR)
    minutes, rest = divmod(rest, MS_PER_MINUTE)
    return f"{hours:02d}:{minutes:02d}:{rest // MS_PER_SECOND:02d}"


def _plain(value: Fraction) -> str:
    return "1" if value == 1 else f"{float(value):.3f}"


def _distribution(
    readings: Sequence[int], choices: Sequence[AnchoredChoice]
) -> dict[int, Fraction]:
    """Exact distribution of the number of covered readings over the rule (choice, onset, end uniform)."""
    out: dict[int, Fraction] = {}
    for choice in choices:
        on = Counter(bisect_left(readings, t) for t in choice.onsets)
        off = Counter(bisect_left(readings, t) for t in choice.ends)
        for a, na in on.items():
            for b, nb in off.items():
                weight = Fraction(
                    na * nb, len(choices) * len(choice.onsets) * len(choice.ends)
                )
                out[b - a] = out.get(b - a, Fraction(0)) + weight
    return out


def observability_table(
    readings_ms: Sequence[int],
    *,
    step_ms: int,
    ks: Sequence[int],
    day_start_ms: int = 0,
    day_end_ms: int = T_DAY_MS,
) -> str:
    """The markdown table of the anchored windows by exact enumeration (``docs/benchmark/builder.md``).

    ``ks`` are the numbers of readings of the duration rows of the design (the caller reads them from
    ``injections.yaml``; none is fixed here). Every figure is an exact fraction of the rule of the module
    docstring over the readings given, not a sample.
    """
    readings = _clean(readings_ms, day_start_ms, day_end_ms)
    shown = ", ".join(_clock(t - day_start_ms) for t in readings)
    intro = (
        f"Readings of the default day ({len(readings)}): {shown}. Grid {step_ms // MS_PER_SECOND} s, "
        f"day end {_clock(day_end_ms - day_start_ms)}. Per row, the first covered reading is uniform among the "
        "feasible ones, the onset and the end uniform on the grid inside the ranges below; "
        "the second column gives the probability of each number of covered readings."
    )
    header = (
        "| k | readings covered by a window: probability | first-reading choices | onsets x ends per choice "
        "| duration min / mean / max (h) | realised: cuff_detached, cuff_silent_bias "
        "| realised: stuck_at without a previous evening (day 0, not drawn) / with one (days 1 to 6) |"
    )
    lines = [intro, "", header, "|---|---|---|---|---|---|---|"]
    hour = Fraction(MS_PER_HOUR)
    for k in ks:
        choices = anchored_choices(
            readings,
            k,
            step_ms=step_ms,
            day_start_ms=day_start_ms,
            day_end_ms=day_end_ms,
        )
        if not choices:
            raise AnchoringError(f"the day has no window of {k} readings")
        distribution = _distribution(readings, choices)
        shapes = ", ".join(f"{len(c.onsets)}x{len(c.ends)}" for c in choices)
        shortest = min(c.ends[0] - c.onsets[-1] for c in choices)
        longest = max(c.ends[-1] - c.onsets[0] for c in choices)
        mean = sum(
            (
                Fraction(c.ends[0] + c.ends[-1], 2)
                - Fraction(c.onsets[0] + c.onsets[-1], 2)
                for c in choices
            ),
            Fraction(0),
        ) / len(choices)
        covered = ", ".join(
            f"{n}: {_plain(p)}" for n, p in sorted(distribution.items())
        )
        at_least_one = sum((p for n, p in distribution.items() if n >= 1), Fraction(0))
        # on day 0 a window whose first covered reading is the first of the day has nothing to freeze
        with_earlier = Fraction(sum(1 for c in choices if c.first > 0), len(choices))
        lines.append(
            f"| {k} | {covered} | {len(choices)} | {shapes} "
            f"| {float(Fraction(shortest) / hour):.2f} / {float(mean / hour):.2f} / {float(Fraction(longest) / hour):.2f} "
            f"| {_plain(at_least_one)} | {_plain(with_earlier)} / {_plain(at_least_one)} |"
        )
    return "\n".join(lines)


def find_block(document: str) -> re.Match[str] | None:
    """The marked block of a document (group 1 is its content), or None."""
    return re.search(
        re.escape(BEGIN_MARK) + r"[^\n]*\n(.*?)" + re.escape(END_MARK),
        document,
        re.DOTALL,
    )


def render_block(table: str) -> str:
    """The marked block, as it stands in the document."""
    return f"{BEGIN_LINE}\n\n{table}\n\n{END_MARK}"
