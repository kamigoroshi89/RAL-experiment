"""Cuff faults anchored to the readings of the day (WS04-T16, ADR-070 (a), (b), (d)).

The windows of ``cuff_detached``, ``cuff_silent_bias`` and ``stuck_at`` are expressed as a number ``k`` of
consecutive cuff readings of the day's stream (the duration rows are in the unit ``readings``, values 1, 2, 3),
not as a time: a window drawn uniformly on the 60 s grid held no reading in most of the draws (ADR-070
context). This module holds the geometry, free of any random state of the builder.

The rule (ADR-070 (a)). Let ``r[0] < ... < r[n-1]`` be the reading instants of the day. The first covered
reading ``i`` is drawn uniformly among the ``n - k + 1`` feasible ones; the onset is drawn uniformly on the
grid in ``(r[i-1], r[i]]`` (from the day start for ``i = 0``); the end is drawn uniformly on the grid in
``(r[i+k-1], r[i+k]]`` (up to the day end after the last reading). The window is ``[onset, end)``, so the
reading at the onset is inside and the next reading (``end <= r[i+k]``) is outside: it covers exactly ``k``
readings and never passes the day end. The onset and the end are independent. Drawing every ``(onset, end)``
pair equally likely instead would make the first covered reading depend on the gaps between readings.

``annotate_reading_counts`` adds ``n_readings_drawn`` (the readings of the fault-free base stream inside the
window: the ``k`` of the rule) to the injection record, next to the ``n_readings_covered`` that the injector
writes after the robot stage (``nav_delay`` and ``manipulation_failure`` run first and can move or remove a
reading, so the effective number is ``k - 1`` or ``k + 1`` in a few percent of the draws; ADR-070 (b)).

``observability_table`` builds the table of ``docs/benchmark/builder.md`` by exact enumeration;
``python tools/anchored_observability_table.py --write`` rewrites it from the configuration files (``--check``
verifies it). The script lives in ``tools/`` because this package must not import the specification.
"""

