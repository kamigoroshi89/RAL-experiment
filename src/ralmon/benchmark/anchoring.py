ANCHORED_SUBTYPES: Final = tuple(sorted(READING_DURATION_SUBTYPES))
_BP: Final = "bp"
BEGIN_MARK: Final = "<!-- observability-table:begin"
END_MARK: Final = "<!-- observability-table:end -->"
BEGIN_LINE: Final = (
    BEGIN_MARK
    + " (generated by python tools/anchored_observability_table.py --write; do not edit by hand) -->"
)


class AnchoringError(ValueError):
    """The arguments of the anchored planner are not usable."""


@dataclasses.dataclass(frozen=True, slots=True)
class AnchoredChoice:
    """One feasible first covered reading: ``first`` is its index, ``onsets`` and ``ends`` the grid instants.

    Every ``(onset, end)`` of ``onsets x ends`` is a window ``[onset, end)`` that covers exactly the ``k``
    readings ``first .. first + k - 1``. Both are ranges of integer ms on the continuing axis of the day.
    """

    first: int
    onsets: range
    ends: range


def _int(name: str, value: object, low: int) -> int:
    if isinstance(value, bool) or not isinstance(value, int | np.integer):
        raise AnchoringError(f"{name} must be an integer, got {value!r}")
    if value < low:
        raise AnchoringError(f"{name} must be at least {low}, got {value}")
    return int(value)


def _clean(readings_ms: Iterable[int], day_start_ms: int, day_end_ms: int) -> list[int]:
    return sorted(
        {
            _int("a reading instant", t, 0)
            for t in readings_ms
            if day_start_ms <= t < day_end_ms
        }
    )


def anchored_choices(
    readings_ms: Iterable[int],
    k: int,
    *,
    step_ms: int,
    day_start_ms: int,
    day_end_ms: int,
) -> tuple[AnchoredChoice, ...]:
    """The feasible first readings of a window of ``k`` readings and their onset and end ranges (module docstring).

    ``readings_ms`` are the reading instants of the day (those outside ``[day_start_ms, day_end_ms)`` are
    ignored), ``step_ms`` the grid of the plan counted from ``day_start_ms``. A first reading with no grid
    instant for its onset or for its end (two readings in one grid cell) is not feasible and is left out.
    The result is empty when the day has fewer than ``k`` readings.
    """
    k = _int("k", k, 1)
    step = _int("step_ms", step_ms, 1)
    start = _int("day_start_ms", day_start_ms, 0)
    stop = _int("day_end_ms", day_end_ms, start + 1)
    times = _clean(readings_ms, start, stop)
    n = len(times)
    choices: list[AnchoredChoice] = []
    for first in range(max(0, n - k + 1)):
        last = first + k - 1
        j_lo = 0 if first == 0 else (times[first - 1] - start) // step + 1
        j_hi = (times[first] - start) // step
        upper = times[last + 1] if last + 1 < n else stop
        e_lo = (times[last] - start) // step + 1
        e_hi = (upper - start) // step
        if j_lo > j_hi or e_lo > e_hi:
            continue
        choices.append(
            AnchoredChoice(
                first,
                range(start + step * j_lo, start + step * (j_hi + 1), step),
                range(start + step * e_lo, start + step * (e_hi + 1), step),
            )
        )
    return tuple(choices)


def draw_anchored_window(
    rng: np.random.Generator, choices: Sequence[AnchoredChoice]
) -> tuple[int, int, int]:
    """``(onset, end, first)``: the first reading uniformly among the choices, then onset and end uniformly."""
    if not choices:
        raise AnchoringError("there is no feasible first reading to draw from")
    choice = choices[int(rng.integers(0, len(choices)))]
    onset = choice.onsets[int(rng.integers(0, len(choice.onsets)))]
    end = choice.ends[int(rng.integers(0, len(choice.ends)))]
    return onset, end, choice.first


def count_readings(
    sorted_readings_ms: Sequence[int], onset_ms: int, end_ms: int
) -> int:
    """The readings of a sorted list inside the window ``[onset_ms, end_ms)``."""
    return bisect_left(sorted_readings_ms, end_ms) - bisect_left(
        sorted_readings_ms, onset_ms
    )


def stream_readings(stream_: ObservedStream) -> list[int]:
    """The sorted reading instants (``t_device_ms`` of the ``bp`` samples) of an observed stream."""
    return sorted({s.t_device_ms for s in stream_.samples if s.signal == _BP})


def annotate_reading_counts(
    records: Iterable[InjectionRecord], base_stream: ObservedStream
) -> tuple[InjectionRecord, ...]:
    """Add ``n_readings_drawn`` to the records of the three anchored subtypes (the others are returned as they are).

    ``base_stream`` is the stream the plan was drawn on, before any injection: the readings of the fault-free
    day inside the window are the ``k`` that the rule drew. The injector wrote ``n_readings_covered`` after the
    robot stage; the truth keeps both (ADR-070 (b)) and every per-k report uses the covered one.
    """
    readings = stream_readings(base_stream)
    out: list[InjectionRecord] = []
    for record in records:
        spec = record.spec
        if (
            spec.cls is not InjectedClass.C2
            or spec.subtype not in READING_DURATION_SUBTYPES
            or spec.duration_ms is None
        ):
            out.append(record)
            continue
        drawn = count_readings(
            readings, spec.onset_ms, spec.onset_ms + spec.duration_ms
        )
        out.append(
            dataclasses.replace(
                record, details={**record.details, "n_readings_drawn": drawn}
            )
        )
    return tuple(out)


